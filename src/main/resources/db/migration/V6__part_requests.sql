CREATE TABLE ff_part_requests (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ticket_id BIGINT NOT NULL REFERENCES ff_tickets(id),
 requested_by_id BIGINT NOT NULL REFERENCES ff_users(id),
 name VARCHAR(120) NOT NULL, quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 99),
 purpose VARCHAR(2000) NOT NULL, reference_url VARCHAR(1000), status VARCHAR(20) NOT NULL,
 reply VARCHAR(2000), reviewed_by_id BIGINT REFERENCES ff_users(id),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL, updated_at TIMESTAMP WITH TIME ZONE NOT NULL, version BIGINT NOT NULL
);
CREATE INDEX idx_part_requests_owner ON ff_part_requests(requested_by_id,id);
CREATE INDEX idx_part_requests_ticket ON ff_part_requests(ticket_id,id);
ALTER TABLE ff_notifications ADD COLUMN part_request_id BIGINT REFERENCES ff_part_requests(id);
