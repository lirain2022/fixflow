CREATE TABLE ff_repair_quotes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ticket_id BIGINT NOT NULL REFERENCES ff_tickets(id),
 created_by_id BIGINT NOT NULL REFERENCES ff_users(id),
 labor_cost NUMERIC(12,2) NOT NULL CHECK (labor_cost >= 0),
 parts_cost NUMERIC(12,2) NOT NULL CHECK (parts_cost >= 0),
 description VARCHAR(2000) NOT NULL,
 status VARCHAR(30) NOT NULL CHECK (status IN ('PENDING','ACCEPTED','CHANGES_REQUESTED')),
 response VARCHAR(2000), responded_by_id BIGINT REFERENCES ff_users(id),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 responded_at TIMESTAMP WITH TIME ZONE,
 version BIGINT NOT NULL
);
CREATE INDEX idx_repair_quotes_ticket ON ff_repair_quotes(ticket_id,id);
