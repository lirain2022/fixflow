CREATE TABLE ff_users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(80) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, role VARCHAR(20) NOT NULL,
 enabled BOOLEAN NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE ff_tickets (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version BIGINT,
 ticket_no VARCHAR(40) UNIQUE, title VARCHAR(120) NOT NULL,
 description VARCHAR(4000) NOT NULL, location VARCHAR(200) NOT NULL,
 category VARCHAR(30) NOT NULL, priority VARCHAR(20) NOT NULL, status VARCHAR(20) NOT NULL,
 created_by_id BIGINT NOT NULL REFERENCES ff_users(id), assigned_to_id BIGINT REFERENCES ff_users(id),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL, updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
 due_at TIMESTAMP WITH TIME ZONE NOT NULL, started_at TIMESTAMP WITH TIME ZONE,
 resolved_at TIMESTAMP WITH TIME ZONE, closed_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_ticket_creator ON ff_tickets(created_by_id, id);
CREATE INDEX idx_ticket_assignee ON ff_tickets(assigned_to_id, status);
CREATE INDEX idx_ticket_status ON ff_tickets(status, due_at);
CREATE TABLE ff_entries (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ticket_id BIGINT NOT NULL REFERENCES ff_tickets(id), author_id BIGINT NOT NULL REFERENCES ff_users(id),
 kind VARCHAR(20) NOT NULL, content VARCHAR(4000) NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 started_at TIMESTAMP WITH TIME ZONE, completed_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_entry_ticket ON ff_entries(ticket_id, id);
CREATE TABLE ff_attachments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ticket_id BIGINT NOT NULL REFERENCES ff_tickets(id), uploaded_by_id BIGINT NOT NULL REFERENCES ff_users(id),
 file_name VARCHAR(200) NOT NULL, storage_key VARCHAR(100) NOT NULL, content_type VARCHAR(40) NOT NULL,
 size BIGINT NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_attachment_ticket ON ff_attachments(ticket_id);
CREATE TABLE IF NOT EXISTS task (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title VARCHAR(100) NOT NULL, description VARCHAR(500), status VARCHAR(255) NOT NULL,
 created_at TIMESTAMP NOT NULL, updated_at TIMESTAMP NOT NULL
);
