CREATE TABLE ff_notifications (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 recipient_id BIGINT NOT NULL REFERENCES ff_users(id),
 ticket_id BIGINT NOT NULL REFERENCES ff_tickets(id),
 kind VARCHAR(30) NOT NULL,
 message VARCHAR(200) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 read_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_notification_recipient_id ON ff_notifications(recipient_id, id);
CREATE INDEX idx_notification_recipient_read ON ff_notifications(recipient_id, read_at);
CREATE INDEX idx_notification_ticket ON ff_notifications(ticket_id);
